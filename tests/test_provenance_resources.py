"""Provenance histories preserve the newest exact suffix without large joins."""

import tracemalloc

import pytest

from cellstine.core import provenance as p


def test_oversized_history_allocates_for_retained_comment_not_discarded_joins():
    notes = [f"discard-{index}-" + "x" * 1000 for index in range(1000)]
    notes += ["kept:first", "kept:second"]
    expected = f"{p.STAGE_PREFIX} build stage | kept:first | kept:second | {p.SIGNATURE}"
    tracemalloc.start()
    try:
        result = p._assemble("build", notes)
        _, peak = tracemalloc.get_traced_memory()
    finally:
        tracemalloc.stop()
    assert result == expected
    assert peak < 128 * 1024


def test_notes_filter_fields_and_keep_first_case_sensitive_occurrence():
    comment = " | ".join(["Generated by CELLSTINE surface stage", "Cú", "A", "Cú", "a", p.SIGNATURE.lower(), "", "A"])
    assert p.stage_of(comment) == "surface"
    assert p.comment_notes(comment) == ["Cú", "A", "a"]
    assert p.stage_of("handwritten") is None
    assert p.comment_notes("handwritten") == ["handwritten"]


def test_restaging_keeps_repeated_new_notes_but_not_repeated_existing_notes():
    original = p.stage_comment("surface", "original")
    result = p.restage_comment(original, "build", "original", "new", "new")
    assert result == f"{p.STAGE_PREFIX} build stage | original | new | new | {p.SIGNATURE}"
    assert p.stage_of(result) == "build"


@pytest.mark.parametrize("delta", [0, 1])
def test_comment_limit_uses_characters_and_discards_oldest_notes(delta):
    base = p.stage_comment("build")
    length = p.MAX_COMMENT_LENGTH - len(base) - len(" | tail") - len(" | ")
    first = "é" * (length + delta)
    result = p.stage_comment("build", first, "tail")
    if delta == 0:
        assert len(result) == p.MAX_COMMENT_LENGTH
        assert p.comment_notes(result) == [first, "tail"]
    else:
        assert result == p.stage_comment("build", "tail")


def test_empty_notes_and_an_overlong_stage_retain_existing_contract():
    assert p.stage_comment("build", "", "  ") == p.stage_comment("build")
    stage = "x" * 300
    result = p.stage_comment(stage, "discard")
    assert result == f"{p.STAGE_PREFIX} {stage} stage | {p.SIGNATURE}"
    assert len(result) > p.MAX_COMMENT_LENGTH
